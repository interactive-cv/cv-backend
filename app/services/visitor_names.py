"""Генерация дружелюбных псевдо-имён для анонимных HR.

Детерминированно из session_id: один и тот же session_id всегда даёт одно имя.
Формат: «Прилагательное Животное» (например «Любопытный Сокол»).
"""
import hashlib

ADJECTIVES = [
    "Любопытный", "Деловой", "Энергичный", "Спокойный", "Быстрый",
    "Мудрый", "Тихий", "Смелый", "Ловкий", "Дружелюбный",
    "Аккуратный", "Находчивый", "Серьёзный", "Весёлый", "Упорный",
    "Задумчивый", "Решительный", "Открытый", "Внимательный", "Честный",
    "Ясный", "Тёплый", "Свежий", "Яркий", "Меткий",
    "Зоркий", "Крепкий", "Лёгкий", "Гибкий", "Звонкий",
]

ANIMALS = [
    "Сокол", "Барсук", "Лиса", "Волк", "Орёл",
    "Медведь", "Заяц", "Рысь", "Сова", "Олень",
    "Бобёр", "Кит", "Дельфин", "Ёж", "Крот",
    "Журавль", "Аист", "Барс", "Тигр", "Лев",
    "Кабан", "Выдра", "Глухарь", "Снегирь", "Дятел",
    "Скворец", "Конь", "Козёл", "Россомаха", "Песец",
    "Морж", "Тюлень", "Омар", "Краб", "Лось",
    "Гепард", "Енот", "Ласка", "Хорёк", "Норка",
]


def generate_visitor_name(session_id: str) -> str:
    """Детерминированно генерирует имя из session_id.

    30 прилагательных × 40 животных = 1200 уникальных комбинаций.
    """
    h = int(hashlib.sha256(session_id.encode()).hexdigest(), 16)
    adj = ADJECTIVES[h % len(ADJECTIVES)]
    animal = ANIMALS[(h >> 16) % len(ANIMALS)]
    return f"{adj} {animal}"
